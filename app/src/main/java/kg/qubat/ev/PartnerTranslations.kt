/** Exact cabinet phrases keep account names, IDs and the driver's translation rules untouched. */
internal fun partnerTranslation(text:String,language:AppLanguage):String? {
    if(language==AppLanguage.RU)return null
    val key=text.trim()
    val translated=partnerPhrases[key]?.let {if(language==AppLanguage.EN)it.first else it.second}
        ?: partnerPatterns.firstNotNullOfOrNull {entry->entry.pattern.matchEntire(key)?.let {match->entry.render(match.groupValues.drop(1),language)}}
        ?: return null
    return text.replace(key,translated)
}
