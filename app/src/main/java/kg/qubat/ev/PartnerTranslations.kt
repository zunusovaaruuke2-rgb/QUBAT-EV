    PartnerTextPattern(Regex("^Excel сохранён · (.+)$")) {g,l->if(l==AppLanguage.EN) "Excel saved · ${g[0]}" else "Excel сакталды · ${g[0]}"},
    PartnerTextPattern(Regex("^Договор: (.+)$")) {g,l->if(l==AppLanguage.EN) "Contract: ${g[0]}" else "Келишим: ${g[0]}"},
    PartnerTextPattern(Regex("^Причина возврата: (.+)$")) {g,l->
        val value=partnerPhrases[g[0]]?.let {if(l==AppLanguage.EN)it.first else it.second} ?: g[0]
        if(l==AppLanguage.EN) "Refund reason: $value" else "Кайтаруунун себеби: $value"
    },
    PartnerTextPattern(Regex("^Подтверждён: (.+)$")) {g,l->if(l==AppLanguage.EN) "Confirmed: ${g[0]}" else "Ырасталды: ${g[0]}"},
    PartnerTextPattern(Regex("^Ответственный: (.+)$")) {g,l->
        val value=partnerPhrases[g[0]]?.let {if(l==AppLanguage.EN)it.first else it.second} ?: g[0]
        if(l==AppLanguage.EN) "Responsible: $value" else "Жооптуу: $value"
    },
    PartnerTextPattern(Regex("^Источник: (.+) · ДЕМО$")) {g,l->if(l==AppLanguage.EN) "Source: ${g[0]} · DEMO" else "Булак: ${g[0]} · ДЕМО"},
    PartnerTextPattern(Regex("^Учётная запись: (.+)$")) {g,l->if(l==AppLanguage.EN) "Account: ${g[0]}" else "Аккаунт: ${g[0]}"}
)
